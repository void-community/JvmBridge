using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;

namespace JvmBridge.Generator.Proxies;

/// <summary>
/// Produces typed C# proxies for Java classes, so agent code calls an application's API without descriptor strings. Each class becomes a <c>readonly struct</c> in <c>JavaProxies.&lt;Package&gt;</c> that wraps a reference: static methods and
/// constructors (<c>New</c>) are static, instance methods use the wrapped reference. Primitives and <c>String</c> map to C# types, and every other object or array is a <c>nint</c> reference on the way in and a <c>JavaLocalReference</c> on the way out.
/// A proxy call looks the method up each time it runs. The writer is pure so that it can run inside an MSBuild task and be tested directly.
/// </summary>
public static class JavaProxySourceWriter
{
    private const string Environment = "global::JvmBridge.Runtime.JavaEnvironment";
    private const string Reference = "global::JvmBridge.Runtime.JavaLocalReference";
    private const string ValueType = "global::JvmBridge.Native.jvalue";
    private const string Values = "global::JvmBridge.Runtime.JavaValue";

    /// <summary>Generates the proxies.</summary>
    /// <param name="classes">The classes to wrap, with their public members.</param>
    /// <returns>The C# source text.</returns>
    public static string Generate(IEnumerable<JavaProxyClass> classes)
    {
        if (classes is null)
            throw new ArgumentNullException(nameof(classes));

        SourceWriter text = new();
        text.Line(text: "// <auto-generated/>");
        text.Line(text: "#nullable enable");

        foreach (IGrouping<string, JavaProxyClass> package in classes.OrderBy(static entry => entry.Name, StringComparer.Ordinal).GroupBy(static entry => PackageOf(entry.Name), StringComparer.Ordinal))
        {
            text.Line();
            text.Line("namespace " + NamespaceOf(package.Key));
            text.Line(text: "{");

            foreach (JavaProxyClass type in package)
                WriteClass(text, type);

            text.Line(text: "}");
        }

        return text.ToString();
    }

    /// <summary>
    /// Generates the proxies from a text description, which is how the build task hands over what it read from the class files without sharing types with this assembly. A line <c>class&#9;com/acme/Service</c> starts a class and
    /// a line <c>member&#9;name&#9;descriptor&#9;static</c> or <c>member&#9;name&#9;descriptor&#9;instance</c> adds a public method or constructor (<c>&lt;init&gt;</c>) to it.
    /// </summary>
    /// <param name="description">The lines of the description.</param>
    /// <returns>The C# source text.</returns>
    public static string GenerateFromText(string description)
    {
        if (description is null)
            throw new ArgumentNullException(nameof(description));

        List<JavaProxyClass> classes = [];
        string? name = null;
        List<JavaProxyMember> members = [];

        foreach (string line in description.Split(['\n'], StringSplitOptions.RemoveEmptyEntries))
        {
            string[] fields = line.TrimEnd(trimChars: ['\r']).Split(separator: ['\t']);

            if (fields.Length == 2 && fields[0] == "class")
            {
                if (name is not null)
                    classes.Add(new JavaProxyClass(name, members));

                name = fields[1];
                members = [];
            }
            else if (fields.Length == 4 && fields[0] == "member" && name is not null)
            {
                members.Add(new JavaProxyMember(fields[1], fields[2], fields[3] == "static"));
            }
            else
            {
                throw new ArgumentException("Unexpected line in the proxy description: " + line, nameof(description));
            }
        }

        if (name is not null)
            classes.Add(new JavaProxyClass(name, members));

        return Generate(classes);
    }

    /// <summary>Turns a Java name into a C# identifier: the first letter is capitalized and characters C# does not allow become underscores.</summary>
    /// <param name="name">A package segment, class name or member name.</param>
    /// <returns>The identifier.</returns>
    public static string ToIdentifier(string name)
    {
        if (string.IsNullOrEmpty(name))
            return "_";

        char[] characters = new char[name.Length];

        for (int index = 0; index < name.Length; index++)
            characters[index] = char.IsLetterOrDigit(name[index]) || name[index] == '_' ? name[index] : '_';

        characters[0] = char.ToUpperInvariant(characters[0]);
        string result = new(characters);

        return char.IsDigit(result[index: 0]) ? "_" + result : result;
    }

    private static string CSharpParameterType(string descriptor)
    {
        return descriptor switch
        {
            "Z" => "bool",
            "B" => "sbyte",
            "C" => "char",
            "S" => "short",
            "I" => "int",
            "J" => "long",
            "F" => "float",
            "D" => "double",
            "Ljava/lang/String;" => "string?",
            _ => "nint"
        };
    }

    private static string CSharpReturnType(string descriptor)
    {
        return descriptor == "V"
            ? "void"
            : descriptor.Length == 1 || descriptor == "Ljava/lang/String;" ? CSharpParameterType(descriptor) : Reference;
    }

    private static string CallMethod(string returnType)
    {
        return returnType switch
        {
            "Z" => "CallBoolean",
            "B" => "CallByte",
            "C" => "CallChar",
            "S" => "CallShort",
            "I" => "CallInt",
            "J" => "CallLong",
            "F" => "CallFloat",
            "D" => "CallDouble",
            "V" => "CallVoid",
            _ => "CallObject"
        };
    }

    private static string DescriptorSuffix(string descriptor)
    {
        List<string> parameters = ParameterTypes(descriptor, out string returnType);

        return "_" + (parameters.Count == 0 ? "Returning" + TypeWord(returnType) : string.Join(separator: "_", parameters.Select(TypeWord)));
    }

    private static List<Entry> Name(IReadOnlyList<JavaProxyMember> members, string structName)
    {
        List<Entry> entries = [];

        foreach (JavaProxyMember member in members.OrderBy(static entry => entry.Name, StringComparer.Ordinal).ThenBy(static entry => entry.Descriptor, StringComparer.Ordinal))
        {
            string name = member.IsConstructor ? "New" : ToIdentifier(member.Name);

            if (name == structName || name == "Handle" || name == "ClassName")
                name += "_";

            string key = name + "(" + string.Join(separator: ",", ParameterTypes(member.Descriptor, out _).Select(CSharpParameterType)) + ")";
            entries.Add(new Entry(member, name, key));
        }

        IEnumerable<IGrouping<string, Entry>> collisions = entries.GroupBy(static entry => entry.Key, StringComparer.Ordinal).Where(static group => group.Count() > 1);
        HashSet<Entry> colliding = [.. collisions.SelectMany(static group => group)];
        HashSet<string> used = new(entries.Where(entry => !colliding.Contains(entry)).Select(static entry => entry.Name), StringComparer.Ordinal);

        for (int index = 0; index < entries.Count; index++)
        {
            Entry entry = entries[index];

            if (!colliding.Contains(entry))
                continue;

            string unique = entry.Name + DescriptorSuffix(entry.Member.Descriptor);

            while (!used.Add(unique))
                unique += "_";

            entries[index] = new Entry(entry.Member, unique, entry.Key);
        }

        return entries;
    }

    private static string NamespaceOf(string package)
    {
        return package.Length == 0 ? "JavaProxies" : "JavaProxies." + string.Join(separator: ".", package.Split(separator: ['/']).Select(ToIdentifier));
    }

    private static string PackageOf(string className)
    {
        int separator = className.LastIndexOf(value: '/');

        return separator < 0 ? string.Empty : className.Substring(startIndex: 0, separator);
    }

    private static List<string> ParameterTypes(string descriptor, out string returnType)
    {
        List<string> parameters = [];
        int index = 1;

        while (index < descriptor.Length && descriptor[index] != ')')
        {
            int start = index;

            while (descriptor[index] == '[')
                index++;

            index = descriptor[index] == 'L' ? descriptor.IndexOf(value: ';', index) + 1 : index + 1;
            parameters.Add(descriptor.Substring(start, index - start));
        }

        returnType = descriptor.Substring(index + 1);

        return parameters;
    }

    private static string Quote(string value)
    {
        return "\"" + value.Replace(oldValue: "\\", newValue: "\\\\").Replace(oldValue: "\"", newValue: "\\\"") + "\"";
    }

    private static string SimpleName(string className)
    {
        int separator = className.LastIndexOf(value: '/');

        return separator < 0 ? className : className.Substring(separator + 1);
    }

    private static string TypeWord(string descriptor)
    {
        if (descriptor.Length == 0)
            return "Void";

        if (descriptor[index: 0] == '[')
            return "Array" + TypeWord(descriptor.Substring(startIndex: 1));

        if (descriptor[index: 0] == 'L')
        {
            string name = descriptor.Substring(startIndex: 1, descriptor.Length - 2);

            return ToIdentifier(SimpleName(name).Replace(oldChar: '$', newChar: '_'));
        }

        return descriptor switch
        {
            "Z" => "Boolean",
            "B" => "Byte",
            "C" => "Char",
            "S" => "Short",
            "I" => "Int",
            "J" => "Long",
            "F" => "Float",
            "D" => "Double",
            _ => "Void"
        };
    }

    private static string ValueFor(string descriptor, string argument)
    {
        return descriptor switch
        {
            "Z" => Values + ".Boolean(" + argument + ")",
            "B" => Values + ".Byte(" + argument + ")",
            "C" => Values + ".Char(" + argument + ")",
            "S" => Values + ".Short(" + argument + ")",
            "I" => Values + ".Int(" + argument + ")",
            "J" => Values + ".Long(" + argument + ")",
            "F" => Values + ".Float(" + argument + ")",
            "D" => Values + ".Double(" + argument + ")",
            "Ljava/lang/String;" => Values + ".Object(" + argument + "Text?.Handle ?? 0)",
            _ => Values + ".Object(" + argument + ")"
        };
    }

    private static void WriteClass(SourceWriter text, JavaProxyClass type)
    {
        string structName = ToIdentifier(SimpleName(type.Name));
        List<Entry> entries = Name(type.Members, structName);
        text.Line(
            "    /// <summary>Typed calls into the Java class <c>" + type.Name + "</c>. It wraps a reference that is valid where it was obtained; promote it to a global reference to keep it.</summary>"
        );
        text.Line("    internal readonly struct " + structName);
        text.Line(text: "    {");
        text.Line(text: "        /// <summary>The internal name of the wrapped Java class.</summary>");
        text.Line("        public const string ClassName = " + Quote(type.Name) + ";");
        text.Line();
        text.Line(text: "        private readonly nint _handle;");
        text.Line();
        text.Line(text: "        /// <summary>Wraps a reference to an instance of the class.</summary>");
        text.Line(text: "        /// <param name=\"handle\">A reference to the Java object.</param>");
        text.Line("        public " + structName + "(nint handle)");
        text.Line(text: "        {");
        text.Line(text: "            _handle = handle;");
        text.Line(text: "        }");
        text.Line();
        text.Line(text: "        /// <summary>Gets the wrapped reference.</summary>");
        text.Line(text: "        public nint Handle => _handle;");

        foreach (Entry entry in entries)
        {
            text.Line();
            WriteMember(text, type.Name, entry);
        }

        text.Line(text: "    }");
    }

    private static void WriteMember(SourceWriter text, string className, Entry entry)
    {
        JavaProxyMember member = entry.Member;
        List<string> parameters = ParameterTypes(member.Descriptor, out string returnType);
        string resultType = member.IsConstructor ? Reference : CSharpReturnType(returnType);
        List<string> declared = [Environment + " environment"];
        bool instance = !member.IsStatic && !member.IsConstructor;

        for (int index = 0; index < parameters.Count; index++)
            declared.Add(CSharpParameterType(parameters[index]) + " argument" + index.ToString(CultureInfo.InvariantCulture));

        string label = member.IsConstructor ? "Creates an instance with" : "Calls";
        text.Line("        /// <summary>" + label + " <c>" + className + "." + member.Name + member.Descriptor + "</c>.</summary>");
        text.Line(
            "        public " + (instance ? string.Empty : "static ") + resultType + " " + entry.Name + "(" + string.Join(separator: ", ", declared) + ")"
        );
        text.Line(text: "        {");
        text.Line(text: "            global::System.ArgumentNullException.ThrowIfNull(environment);");
        text.Line(
            "            using " + Reference + " type = " + (instance ? "environment.GetObjectClass(_handle);" : "environment.FindClass(ClassName);")
        );
        text.Line(
            "            nint method = environment.GetMethod(type.Handle, " + Quote(member.Name) + ", " + Quote(member.Descriptor) + (member.IsStatic ? ", isStatic: true);" : ");")
        );
        List<string> values = [];

        for (int index = 0; index < parameters.Count; index++)
        {
            string argument = "argument" + index.ToString(CultureInfo.InvariantCulture);

            if (parameters[index] == "Ljava/lang/String;")
            {
                text.Line(
                    "            using " + Reference + "? " + argument + "Text = " + argument + " is null ? null : environment.NewString(" + argument + ");"
                );
            }

            values.Add(ValueFor(parameters[index], argument));
        }

        text.Line(
            "            global::System.ReadOnlySpan<" + ValueType + "> arguments = " + (values.Count == 0 ? "default;" : "[" + string.Join(separator: ", ", values) + "];")
        );

        if (member.IsConstructor)
        {
            text.Line(text: "            return environment.NewObject(type.Handle, method, arguments);");
        }
        else
        {
            string receiver = instance ? "_handle" : "type.Handle";
            string call = "environment." + CallMethod(returnType) + "(" + receiver + ", method, arguments" + (member.IsStatic ? ", isStatic: true)" : ")");

            if (returnType == "Ljava/lang/String;")
            {
                text.Line("            using " + Reference + " result = " + call + ";");
                text.Line(text: "            return environment.GetString(result.Handle);");
            }
            else
            {
                text.Line("            " + (returnType == "V" ? string.Empty : "return ") + call + ";");
            }
        }

        text.Line(text: "        }");
    }

    private sealed class Entry
    {
        public Entry(JavaProxyMember member, string name, string key)
        {
            Member = member;
            Name = name;
            Key = key;
        }

        public string Key { get; }

        public JavaProxyMember Member { get; }

        public string Name { get; }
    }
}
