using System;
using System.Collections.Generic;
using System.Linq;

namespace JvmBridge.Generator;

/// <summary>
/// Produces the <c>JavaClasses</c> source for compiled Java helper classes. It is pure so it can run inside an MSBuild task and be tested directly: the package's build targets read the class files
/// and hand their bytes here, because a source generator may neither read binary files nor do file I/O.
/// </summary>
public static class JavaClassSourceWriter
{
    /// <summary>Generates source that exposes each top-level class as a typed <c>JavaClassDefinition</c>, nested by package, for example <c>JavaClasses.Legacyforgepatcher.Collections</c>.</summary>
    /// <param name="classes">The compiled classes: the path relative to the output directory, such as <c>pkg/Name$Inner.class</c>, and the class-file bytes.</param>
    /// <returns>The C# source text.</returns>
    public static string Generate(IEnumerable<KeyValuePair<string, byte[]>> classes)
    {
        if (classes is null)
            throw new ArgumentNullException(nameof(classes));

        Dictionary<string, List<KeyValuePair<string, byte[]>>> groups = new(StringComparer.Ordinal);

        foreach (KeyValuePair<string, byte[]> pair in classes.Select(static entry => new KeyValuePair<string, byte[]>(Normalize(entry.Key), entry.Value)).OrderBy(static entry => entry.Key, StringComparer.Ordinal))
        {
            string top = TopLevelName(pair.Key);

            if (!groups.TryGetValue(top, out List<KeyValuePair<string, byte[]>>? members))
                groups.Add(top, members = []);

            members.Add(pair);
        }

        Node root = new();

        foreach (string top in groups.Keys.OrderBy(static name => name, StringComparer.Ordinal))
            root.Add(top.Split(separator: ['/']), groups[top]);

        SourceWriter text = new();
        text.Line(text: "// <auto-generated/>");
        text.Line(text: "#nullable enable");
        text.Line(text: "internal static class JavaClasses");
        text.Line(text: "{");
        root.Write(text, indent: 1);
        text.Line(text: "}");

        return text.ToString();
    }

    /// <summary>Turns a Java package or class name into a C# identifier: the first letter is capitalized (which also keeps it from being a keyword) and characters C# does not allow become underscores.</summary>
    /// <param name="name">A package segment or class name.</param>
    /// <returns>The identifier.</returns>
    public static string ToIdentifier(string name)
    {
        if (string.IsNullOrEmpty(name))
            return "_";

        char[] characters = new char[name.Length];

        for (int index = 0; index < name.Length; index++)
        {
            char character = name[index];
            bool valid = char.IsLetterOrDigit(character) || character == '_';
            characters[index] = valid ? character : '_';
        }

        characters[0] = char.ToUpperInvariant(characters[0]);
        string identifier = (char.IsDigit(name[index: 0]) ? "_" : string.Empty) + new string(characters);

        return identifier;
    }

    private static string Definition(string name, byte[] bytes, string indent, List<KeyValuePair<string, byte[]>> nested)
    {
        string arguments = Literal(name) + ", global::System.Convert.FromBase64String(" + Literal(Convert.ToBase64String(bytes)) + ")";

        if (nested.Count == 0)
            return "new global::JvmBridge.Agents.JavaClassDefinition(" + arguments + ")";

        string members = string.Concat(nested.Select(inner => indent + "    " + Definition(inner.Key, inner.Value, indent + "    ", []) + ",\n"));

        return "new global::JvmBridge.Agents.JavaClassDefinition(" + arguments + ", nestedClasses:\n" + indent + "[\n" + members + indent + "])";
    }

    private static string Literal(string value)
    {
        return "\"" + value.Replace(oldValue: "\\", newValue: "\\\\").Replace(oldValue: "\"", newValue: "\\\"") + "\"";
    }

    private static string Normalize(string path)
    {
        string normalized = path.Replace(oldChar: '\\', newChar: '/');

        return normalized.EndsWith(value: ".class", StringComparison.Ordinal) ? normalized.Substring(startIndex: 0, normalized.Length - ".class".Length) : normalized;
    }

    private static string TopLevelName(string name)
    {
        int slash = name.LastIndexOf(value: '/');
        int dollar = name.IndexOf(value: '$', slash + 1);

        return dollar > slash + 1 ? name.Substring(startIndex: 0, dollar) : name;
    }

    private sealed class Node
    {
        private readonly SortedDictionary<string, Node> _children = new(StringComparer.Ordinal);
        private readonly List<KeyValuePair<string, List<KeyValuePair<string, byte[]>>>> _classes = [];

        public void Add(string[] path, List<KeyValuePair<string, byte[]>> members)
        {
            Node current = this;

            for (int index = 0; index < path.Length - 1; index++)
            {
                if (!current._children.TryGetValue(path[index], out Node? child))
                    current._children.Add(path[index], child = new Node());

                current = child;
            }

            current._classes.Add(new KeyValuePair<string, List<KeyValuePair<string, byte[]>>>(path[path.Length - 1], members));
        }

        public void Write(SourceWriter text, int indent)
        {
            string pad = new(c: ' ', indent * 4);
            HashSet<string> used = new(StringComparer.Ordinal);

            foreach (KeyValuePair<string, Node> child in _children)
            {
                string identifier = Unique(ToIdentifier(child.Key), used);
                text.Line(pad + "internal static class " + identifier);
                text.Line(pad + "{");
                child.Value.Write(text, indent + 1);
                text.Line(pad + "}");
            }

            foreach (KeyValuePair<string, List<KeyValuePair<string, byte[]>>> type in _classes)
            {
                string identifier = Unique(ToIdentifier(type.Key.Substring(type.Key.LastIndexOf(value: '/') + 1)), used);
                KeyValuePair<string, byte[]> top = type.Value.FirstOrDefault(member => member.Key.IndexOf(value: '$', member.Key.LastIndexOf(value: '/') + 1) < 0);

                if (top.Key is null)
                    continue;

                List<KeyValuePair<string, byte[]>> nested = [.. type.Value.Where(member => member.Key != top.Key)];
                text.Line(
                    pad + "internal static global::JvmBridge.Agents.JavaClassDefinition " + identifier + " { get; } = " + Definition(top.Key, top.Value, pad, nested) + ";"
                );
            }
        }

        private static string Unique(string identifier, HashSet<string> used)
        {
            string candidate = identifier;

            while (!used.Add(candidate))
                candidate += "_";

            return candidate;
        }
    }
}
