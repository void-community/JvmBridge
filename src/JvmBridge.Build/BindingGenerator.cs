using System.Net;
using System.Text.RegularExpressions;

using JvmBridge.Build.Infrastructure;

namespace JvmBridge.Build;

internal sealed partial class BindingGenerator(RepositoryContext repository, ProcessRunner processRunner)
{
    private readonly ProcessRunner _processRunner = processRunner;
    private readonly RepositoryContext _repository = repository;

    public async Task GenerateAsync(bool check, CancellationToken cancellationToken)
    {
        using TemporaryDirectory temporary = new(prefix: "jvmbridge-bindings-");

        string temporaryOutput = Path.Combine(temporary.Path, path2: "Bindings.cs");
        List<string> command = [];
        string? clangSharp = Environment.GetEnvironmentVariable(variable: "CLANGSHARP");

        if (clangSharp is not null)
            command.Add(clangSharp);
        else
            command.AddRange(collection: ["dotnet", "tool", "run", "ClangSharpPInvokeGenerator", "--"]);

        command.AddRange(collection:
        [
            "-f",
            "headers/jni.h",
            "headers/jvmti.h",
            "-I",
            "shim",
            "-I",
            "headers",
            "-I",
            "headers/linux",
            "-x",
            "c",
            "-a",
            "--target=aarch64-unknown-linux-gnu",
            "-n",
            "JvmBridge.Native",
            "-o",
            temporaryOutput,
            "-c",
            "codegen=latest",
            "-g",
            "helper-types",
            "file-scoped-namespaces",
            "macro-bindings",
            "doc-includes",
            "-e",
            "Agent_OnLoad",
            "Agent_OnAttach",
            "Agent_OnUnload",
            "JNI_OnLoad",
            "JNI_OnUnload",
            "JNI_CreateJavaVM",
            "JNI_GetCreatedJavaVMs",
            "JNI_GetDefaultJavaVMInitArgs",
            "-r",
            "jlong=long",
            "-wcc",
            "*=Winapi",
        ]);

        await _processRunner
            .RunCheckedAsync(command,
                timeout: TimeSpan.FromMinutes(minutes: 5),
                workingDirectory: _repository.PathFromRoot(parts: ["src", "JvmBridge.Build"]),
                echo: true,
                cancellationToken: cancellationToken)
            .ConfigureAwait(continueOnCapturedContext: false);

        string bindings = await File.ReadAllTextAsync(temporaryOutput, cancellationToken)
            .ConfigureAwait(continueOnCapturedContext: false);

        bindings = VariadicSlotRewriter.Rewrite(bindings);

        bindings = DocumentationIncludeRegex().Replace(bindings,
            static match => $"{GroupValue(match, index: 1)}/// <summary>\n{GroupValue(match, index: 1)}/// Provides the pinned OpenJDK native declaration for <c>{WebUtility.HtmlEncode(GroupValue(match, index: 2))}</c>.\n{GroupValue(match, index: 1)}/// </summary>");

        bindings = AddMissingDocumentation(bindings);
        bindings = "// <auto-generated/>\n#pragma warning disable CS8981 // Preserve native identifiers.\n// OpenJDK declarations: see NOTICE.md.\n" + bindings;
        bindings = TextFile.NormalizeLineEndings(bindings);

        string outputPath = _repository.PathFromRoot(parts: ["src", "JvmBridge", "Native", "Generated", "Bindings.g.cs"]);

        if (check)
        {
            string existing = File.Exists(outputPath)
                ? await File.ReadAllTextAsync(outputPath, cancellationToken).ConfigureAwait(continueOnCapturedContext: false)
                : string.Empty;

            if (!File.Exists(outputPath) || !string.Equals(existing, bindings, StringComparison.Ordinal))
                throw new InvalidOperationException(message: "Generated bindings are stale. Run `dotnet build src/JvmBridge.Build -c Release -t:Generate`.");
        }
        else
        {
            TextFile.Write(outputPath, bindings);
        }

        ConsoleOutput.WriteLine(check ? "Generated bindings verified." : "Generated bindings written.");
    }

    internal static string AddMissingDocumentation(string source)
    {
        List<string> documented = [];

        using StringReader reader = new(source);

        while (reader.ReadLine() is { } line)
        {
            if (line == "public static partial class Methods")
                documented.AddRange(collection: ["/// <summary>", "/// Provides constants copied from the pinned OpenJDK headers.", "/// </summary>"]);

            Match constant = ConstantRegex().Match(line);

            if (constant.Success)
            {
                string? attribute = null;

                if (documented.Count > 0 && documented.Last().TrimStart().StartsWith(value: "[NativeTypeName(", StringComparison.Ordinal))
                {
                    attribute = documented.Last();

                    documented.RemoveAt(documented.Count - 1);
                }

                string indentation = GroupValue(constant, name: "indent");
                string name = WebUtility.HtmlEncode(GroupValue(constant, name: "name"));

                documented.AddRange(collection:
                [
                    $"{indentation}/// <summary>",
                    $"{indentation}/// Provides the pinned OpenJDK native constant <c>{name}</c>.",
                    $"{indentation}/// </summary>",
                ]);

                if (attribute is not null)
                    documented.Add(attribute);
            }

            Match bitfield = BitfieldRegex().Match(line);

            if (bitfield.Success)
            {
                string indentation = GroupValue(bitfield, name: "indent");
                string name = WebUtility.HtmlEncode(GroupValue(bitfield, name: "name"));

                documented.AddRange(collection:
                [
                    $"{indentation}/// <summary>",
                    $"{indentation}/// Stores the packed JVMTI capability flags in <c>{name}</c>.",
                    $"{indentation}/// </summary>",
                ]);
            }

            documented.Add(line);
        }

        return string.Join(separator: '\n', documented) + "\n";
    }

    [GeneratedRegex("^(?<indent>[ \\t]*)public uint (?<name>_bitfield[0-9]+);$", RegexOptions.CultureInvariant)]
    private static partial Regex BitfieldRegex();

    [GeneratedRegex("^(?<indent>[ \\t]*)public const \\S+ (?<name>[A-Za-z_][A-Za-z0-9_]*) = .+;$", RegexOptions.CultureInvariant)]
    private static partial Regex ConstantRegex();

    [GeneratedRegex("^([ \\t]*)/// <include file='[^']+' path='doc/member\\[@name=\"([^\"]+)\"\\]/\\*' />$",
        RegexOptions.Multiline | RegexOptions.CultureInvariant)]
    private static partial Regex DocumentationIncludeRegex();

    private static string GroupValue(Match match, int index)
    {
        return match.Groups.Cast<Group>().ElementAt(index).Value;
    }

    private static string GroupValue(Match match, string name)
    {
        return match.Groups[name].Value;
    }
}
